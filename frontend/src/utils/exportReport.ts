import jsPDF from 'jspdf'
import type { Audit } from '../types'
import { categoryLabel } from './helpers'

export async function exportAuditReport(audit: Audit): Promise<void> {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const pageW = 210
  const margin = 20
  const contentW = pageW - margin * 2
  let y = 0

  const navy = [30, 58, 95] as [number, number, number]
  const blue = [37, 99, 235] as [number, number, number]
  const slate = [100, 116, 139] as [number, number, number]
  const red = [220, 38, 38] as [number, number, number]
  const orange = [234, 88, 12] as [number, number, number]
  const amber = [217, 119, 6] as [number, number, number]
  const blueLight = [59, 130, 246] as [number, number, number]
  const slateLight = [148, 163, 184] as [number, number, number]

  function addPage() {
    doc.addPage()
    y = margin
  }

  function checkY(needed: number) {
    if (y + needed > 277) {
      addPage()
    }
  }

  function drawRect(x: number, yPos: number, w: number, h: number, r: [number, number, number]) {
    doc.setFillColor(...r)
    doc.rect(x, yPos, w, h, 'F')
  }

  function setFont(size: number, style: 'normal' | 'bold' = 'normal', color: [number, number, number] = [30, 41, 59]) {
    doc.setFontSize(size)
    doc.setFont('helvetica', style)
    doc.setTextColor(...color)
  }

  // ─── Page 1: Cover ───
  drawRect(0, 0, pageW, 297, navy)

  // Logo area
  doc.setFillColor(37, 99, 235)
  doc.roundedRect(margin, 40, 16, 16, 3, 3, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.text('CL', margin + 5, 51)

  doc.setFontSize(22)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  doc.text('CivicLens AI', margin + 20, 52)

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(...slateLight)
  doc.text('Usability Audit Report', margin + 20, 60)

  // Divider
  doc.setDrawColor(37, 99, 235)
  doc.setLineWidth(0.5)
  doc.line(margin, 75, pageW - margin, 75)

  // Title block
  doc.setFontSize(28)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  const domainText = (() => { try { return new URL(audit.url).hostname } catch { return audit.url } })()
  const titleLines = doc.splitTextToSize(domainText, contentW)
  doc.text(titleLines, margin, 100)

  doc.setFontSize(14)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(...slateLight)
  const taskLines = doc.splitTextToSize(`Task: ${audit.task}`, contentW)
  doc.text(taskLines, margin, 118)

  // Score box
  const score = audit.metadata?.overall_score ?? 0
  const scoreCol: [number, number, number] = score >= 80 ? [22, 163, 74] : score >= 60 ? [217, 119, 6] : [220, 38, 38]
  doc.setFillColor(...scoreCol)
  doc.roundedRect(margin, 140, 60, 40, 4, 4, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(32)
  doc.setFont('helvetica', 'bold')
  doc.text(String(score), margin + 12, 168)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('/ 100', margin + 38, 168)
  doc.setFontSize(9)
  doc.text('Overall Score', margin + 9, 176)

  // Stats
  const stats = [
    { label: 'Findings', value: String(audit.findings.length) },
    { label: 'Critical', value: String(audit.findings.filter(f => f.severity === 'critical').length) },
    { label: 'Pages', value: String(audit.metadata?.pages_inspected ?? '-') },
    { label: 'Checks', value: String(audit.metadata?.checks_run ?? '-') },
  ]
  stats.forEach((s, i) => {
    const sx = margin + 70 + i * 32
    doc.setFillColor(255, 255, 255, 0.1)
    doc.setFillColor(14, 30, 60)
    doc.roundedRect(sx, 140, 28, 40, 3, 3, 'F')
    doc.setTextColor(255, 255, 255)
    doc.setFontSize(20)
    doc.setFont('helvetica', 'bold')
    doc.text(s.value, sx + 14, 165, { align: 'center' })
    doc.setFontSize(8)
    doc.setFont('helvetica', 'normal')
    doc.setTextColor(...slateLight)
    doc.text(s.label, sx + 14, 174, { align: 'center' })
  })

  // Date & disclaimer
  doc.setFontSize(9)
  doc.setTextColor(...slateLight)
  doc.text(`Generated: ${new Date().toLocaleString()}`, margin, 220)
  doc.text(`Audit ID: ${audit.id}`, margin, 228)

  doc.setFontSize(8)
  const disclaimer = 'This report is generated by automated analysis tools and AI-assisted heuristics. Findings should be reviewed by a qualified accessibility or UX professional before acting on recommendations. AI-suggested findings have not been manually verified.'
  const disclaimerLines = doc.splitTextToSize(disclaimer, contentW)
  doc.text(disclaimerLines, margin, 255)

  // ─── Page 2: Executive Summary ───
  addPage()

  setFont(18, 'bold', navy)
  doc.text('Executive Summary', margin, y)
  y += 8

  doc.setDrawColor(...blue)
  doc.setLineWidth(0.5)
  doc.line(margin, y, pageW - margin, y)
  y += 8

  if (audit.metadata?.summary) {
    setFont(10, 'normal', [51, 65, 85])
    const summaryLines = doc.splitTextToSize(audit.metadata.summary, contentW)
    doc.text(summaryLines, margin, y)
    y += summaryLines.length * 5 + 6
  }

  // Severity breakdown
  checkY(60)
  setFont(13, 'bold', navy)
  doc.text('Findings by Severity', margin, y)
  y += 6

  const severities: Array<{ key: string; label: string; color: [number, number, number] }> = [
    { key: 'critical', label: 'Critical', color: red },
    { key: 'high', label: 'High', color: orange },
    { key: 'medium', label: 'Medium', color: amber },
    { key: 'low', label: 'Low', color: blueLight },
    { key: 'info', label: 'Info', color: slate },
  ]

  severities.forEach(s => {
    const count = audit.findings.filter(f => f.severity === s.key).length
    checkY(10)
    drawRect(margin, y, 4, 7, s.color)
    setFont(10, 'normal', [30, 41, 59])
    doc.text(`${s.label}:`, margin + 7, y + 5.5)
    setFont(10, 'bold', [30, 41, 59])
    doc.text(String(count), margin + 30, y + 5.5)
    const barW = count > 0 ? Math.min((count / audit.findings.length) * (contentW - 50), contentW - 50) : 0
    drawRect(margin + 40, y + 1, barW, 5, s.color)
    y += 10
  })

  y += 6

  // Categories breakdown
  checkY(40)
  setFont(13, 'bold', navy)
  doc.text('Findings by Category', margin, y)
  y += 6

  const categories = ['accessibility', 'navigation', 'content_clarity', 'form_usability', 'information_architecture', 'mobile_usability']
  categories.forEach(cat => {
    const count = audit.findings.filter(f => f.category === cat).length
    if (count === 0) return
    checkY(8)
    setFont(9, 'normal', [51, 65, 85])
    const label = categoryLabel(cat as Parameters<typeof categoryLabel>[0])
    doc.text(`${label}:`, margin, y + 4)
    setFont(9, 'bold', [30, 41, 59])
    doc.text(String(count), margin + 55, y + 4)
    y += 8
  })

  // ─── Page 3+: Findings ───
  addPage()

  setFont(18, 'bold', navy)
  doc.text('Detailed Findings', margin, y)
  y += 8
  doc.setDrawColor(...blue)
  doc.setLineWidth(0.5)
  doc.line(margin, y, pageW - margin, y)
  y += 8

  audit.findings.forEach((finding, idx) => {
    checkY(50)

    const sevColor: Record<string, [number, number, number]> = {
      critical: red, high: orange, medium: amber, low: blueLight, info: slate
    }
    const color = sevColor[finding.severity] ?? slate

    // Finding header
    drawRect(margin, y, contentW, 10, [248, 250, 252])
    drawRect(margin, y, 3, 10, color)
    setFont(10, 'bold', [30, 41, 59])
    doc.text(`${idx + 1}. ${finding.title}`, margin + 6, y + 6.5)
    y += 12

    // Badges
    setFont(8, 'bold', color)
    doc.text(finding.severity.toUpperCase(), margin, y + 3)
    setFont(8, 'normal', slate)
    doc.text(`| ${categoryLabel(finding.category)}`, margin + 22, y + 3)
    doc.text(`| ${finding.detection_type.replace('_', ' ')}`, margin + 60, y + 3)
    doc.text(`| Confidence: ${Math.round(finding.confidence * 100)}%`, margin + 90, y + 3)
    y += 8

    // Page URL
    setFont(8, 'normal', slate)
    doc.text(`Page: ${finding.page_url}`, margin, y)
    y += 7

    // Evidence
    checkY(20)
    setFont(9, 'bold', navy)
    doc.text('Evidence', margin, y)
    y += 4
    setFont(8.5, 'normal', [51, 65, 85])
    drawRect(margin, y, contentW, 1, [226, 232, 240])
    y += 2
    const evLines = doc.splitTextToSize(finding.evidence, contentW - 4)
    doc.text(evLines, margin + 2, y + 3)
    y += evLines.length * 4.5 + 5

    // Why it matters
    checkY(20)
    setFont(9, 'bold', navy)
    doc.text('Why It Matters', margin, y)
    y += 4
    setFont(8.5, 'normal', [51, 65, 85])
    const ratLines = doc.splitTextToSize(finding.rationale, contentW)
    doc.text(ratLines, margin, y)
    y += ratLines.length * 4.5 + 4

    // Fix
    checkY(20)
    setFont(9, 'bold', [22, 163, 74])
    doc.text('Recommended Fix', margin, y)
    y += 4
    setFont(8.5, 'normal', [51, 65, 85])
    const fixLines = doc.splitTextToSize(finding.fix, contentW)
    doc.text(fixLines, margin, y)
    y += fixLines.length * 4.5 + 8

    // Divider
    doc.setDrawColor(226, 232, 240)
    doc.setLineWidth(0.3)
    doc.line(margin, y, pageW - margin, y)
    y += 6
  })

  // ─── Last Page: Methodology & Limitations ───
  addPage()

  setFont(18, 'bold', navy)
  doc.text('Methodology & Limitations', margin, y)
  y += 8
  doc.setDrawColor(...blue)
  doc.setLineWidth(0.5)
  doc.line(margin, y, pageW - margin, y)
  y += 8

  const sections = [
    {
      title: 'Audit Methodology',
      body: 'CivicLens AI audits government websites using a combination of automated rule-based checks and AI-assisted heuristic analysis. The audit inspects HTML structure, ARIA attributes, link text, form labeling, navigation depth, and content readability. Scores are calculated based on the number and severity of findings relative to checks run.',
    },
    {
      title: 'Automated Checks',
      body: 'Rule-based checks detect objectively verifiable issues: missing alt text, invalid ARIA roles, absent form labels, broken skip links, and color contrast failures. These findings carry high confidence scores.',
    },
    {
      title: 'AI-Assisted Analysis',
      body: 'When a Gemini API key is configured, AI-assisted analysis evaluates content clarity, navigation logic, and citizen experience heuristics. AI-suggested findings are labeled "ai_suggested" and should be treated as hypotheses requiring human verification.',
    },
    {
      title: 'Limitations',
      body: 'This tool performs static analysis and cannot replicate a full user session. It does not test JavaScript-heavy interactions, authentication flows, or backend form validation. Findings are not a substitute for a professional accessibility audit or WCAG compliance assessment.',
    },
    {
      title: 'Responsible Use',
      body: 'This tool is intended to help governments improve public services. Reports should not be used to make definitive compliance or legal claims. Always engage with affected communities when redesigning government services.',
    },
  ]

  sections.forEach(s => {
    checkY(30)
    setFont(11, 'bold', navy)
    doc.text(s.title, margin, y)
    y += 5
    setFont(9, 'normal', [51, 65, 85])
    const lines = doc.splitTextToSize(s.body, contentW)
    doc.text(lines, margin, y)
    y += lines.length * 4.5 + 7
  })

  // Footer on last page
  checkY(15)
  doc.setDrawColor(226, 232, 240)
  doc.setLineWidth(0.3)
  doc.line(margin, y, pageW - margin, y)
  y += 5
  setFont(8, 'normal', slate)
  doc.text('CivicLens AI — civiclens.ai', margin, y)
  doc.text(`Generated ${new Date().toLocaleString()}`, pageW - margin, y, { align: 'right' })

  doc.save(`civiclens-audit-${audit.id}-${new Date().toISOString().split('T')[0]}.pdf`)
}
